const MESSAGES: Record<UiLocale, Record<UiMessageKey, string>> = {
  en: EN_MESSAGES,
  "zh-CN": ZH_CN_MESSAGES,
};

export function uiMessage(
  locale: UiLocale,
  key: UiMessageKey,
  values: Record<string, string | number> = {},
): string {
  return MESSAGES[locale][key].replace(
    /\{([a-zA-Z][a-zA-Z0-9]*)\}/gu,
    (placeholder, name: string) =>
      name in values ? terminalLine(values[name], 512) : placeholder,
  );
}

export function detectUiLocale(
  env: NodeJS.ProcessEnv = process.env,
  runtimeLocale = Intl.DateTimeFormat().resolvedOptions().locale,
): UiLocale {
  const candidate =
    env.LC_ALL?.trim() ||
    env.LC_MESSAGES?.trim() ||
    env.LANGUAGE?.trim() ||
    env.LANG?.trim() ||
    runtimeLocale;
  return /^zh(?:[_-]|$)/iu.test(candidate) ? "zh-CN" : "en";
}
